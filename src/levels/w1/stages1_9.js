export function emmyAdvice19(state) {
  const { here, current, goal, done, cover, base, treeWord, torusHits } = state
  if (!current) return [E('Every tower is done. Pick up every Tree Seed, then walk north past the Stack Outflow into the Warp Portal.')]
  if (here.site !== current) {
    const name = STATIONS[current]?.blueprint || current
    return [E(`I’m right behind you. Next deck: ${name}. Follow the map’s NEXT ring. Fight the beasts on the open commons with the Lash (1): a projective specter needs its two lashes close together, a Klein bottle three.`)]
  }
  if (!goal) return [E('This deck is finished. Follow the map’s NEXT ring.')]
  if (goal.type === 'cover') {
    const g = state.glue || {}
    if (!state.coverOk)
      return [
        E(`Right now $a$ ${g.a ? 'swaps the sheets' : 'keeps each sheet'} and $b$ ${g.b ? 'swaps them' : 'keeps them'}. Think: for $a$ alone not to close but $a²$ to close, $a$ has to swap the two sheets. For $b$ to close, $b$ has to keep them. Clasp (5) the port of any letter that’s wrong.`),
      ]
    return [E('The tower matches the slate. Read the lift off it and answer the Clasp.')]
  }
  if (goal.type === 'start') {
    if (base !== goal.targetBase) return [E(`Lash the Stack sentinel (1). Each lash moves the start one sheet along. It’s on sheet ${base + 1}; take it to sheet 3 and read the slate.`)]
    return [E('The start’s moved. Walk on once we’re done talking.')]
  }
  if (goal.type === 'tree') {
    const left = (goal.targets || []).filter((w) => !treeWord?.includes(w))
    if (left.length) return [E(`Reach these reduced words on the tree: ${left.map((w) => letterText(w[0]) + (w.slice(1) ? ' …' : '')).join(', ')}`)]
    return [E('Every marked word reached. On to the torus deck.')]
  }
  if (goal.type === 'torus') {
    const left = (goal.loops || []).filter((l) => !torusHits?.[l.word])
    if (left.length) return [E(`Compass (6) the ${left[0].label} loop pedestal and pick its $(m,n)$ on the grid.`)]
    return [E('Both lattice readings are done.')]
  }
  return [E('Lash Liftlings on their own sheet. Lost? I’m right here. Press E.')]
}

